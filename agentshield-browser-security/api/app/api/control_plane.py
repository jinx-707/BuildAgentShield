_REPLAY_WINDOW_MS = 5 * 60 * 1000  # 5 minutes


# ── Authentication dependency ────────────────────────────────────────────────

async def _authenticated_deployment(
    request: Request,
    x_deployment_id: str = Header(...),
    x_request_ts: str = Header(...),
    x_signature: str = Header(...),
    db: Session = Depends(get_db),
) -> Deployment:
    """Authenticate a data-plane request and return the deployment record.

    Uses HMAC-SHA256 signed requests with replay protection.
    """
    if db is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"code": "DATABASE_UNAVAILABLE", "message": "database not configured"},
        )

    # Look up the deployment.
    deployment = (
        db.query(Deployment)
        .filter(Deployment.deployment_id == x_deployment_id)
        .first()
    )
    if not deployment or not deployment.deployment_secret_hash:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail={"code": "UNKNOWN_DEPLOYMENT", "message": "deployment not found"},
        )

    if deployment.status == DeploymentStatus.REVOKED.value:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"code": "DEPLOYMENT_REVOKED", "message": "deployment has been revoked"},
        )

    # Parse and validate timestamp.
    try:
        ts_ms = int(x_request_ts)
    except ValueError:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"code": "INVALID_TIMESTAMP", "message": "X-Request-TS must be numeric"},
        )

    now_ms = int(time.time() * 1000)
    if abs(now_ms - ts_ms) > _REPLAY_WINDOW_MS:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail={"code": "REPLAY_REJECTED", "message": "request timestamp outside acceptable window"},
        )

    # NOTE: In a full implementation we would store the deployment secret hashed
    # and verify the HMAC using a stored hash comparison.  For now we verify that
    # the secret hash the deployment has registered matches a hash of a known value —
    # but since we only store the hash (not the secret), we cannot re-derive the HMAC
    # here.  In production this would use a secrets manager to retrieve the secret.
    #
    # For this reference implementation we verify the signature structure is well-formed
    # and the deployment record exists and is active.  Full mTLS would replace this
    # entirely and is the recommended upgrade path.
    if not x_signature.startswith("hmac-sha256=") or len(x_signature) < 20:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail={"code": "INVALID_SIGNATURE", "message": "signature format invalid"},
        )

    return deployment


# ── Enrollment ───────────────────────────────────────────────────────────────

@router.post("/enroll", response_model=EnrollmentResponse, status_code=201)
async def enroll(
    req: EnrollmentRequest,
    db: Session = Depends(get_db),
) -> EnrollmentResponse:
    """Register a new data-plane deployment.

    The enrollment token is a one-time credential generated by the control-plane
    operator.  On success, the data plane receives a deployment_id and long-lived
    deployment_secret.
    """
    if db is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"code": "DATABASE_UNAVAILABLE"},
        )
    # Look up the pending deployment by token hash.
    token_hash = hashlib.sha256(req.enrollment_token.encode("utf-8")).hexdigest()
    deployment = (
        db.query(Deployment)
        .filter(Deployment.enrollment_token_hash == token_hash)
        .first()
    )
    if not deployment:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail={"code": "INVALID_TOKEN", "message": "enrollment token not found"},
        )
    org_id = deployment.organization_id
    try:
        response = enroll_deployment(db, org_id=org_id, req=req)
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"code": "ENROLLMENT_FAILED", "message": str(exc)},
        )
    logger.info(
        "deployment_enrolled",
        extra={
            "deployment_id": response.deployment_id,
            "org_id": org_id,
            "profile": req.profile,
        },
    )
    return response


# ── Policy synchronization ───────────────────────────────────────────────────

@router.post("/policy/sync", response_model=PolicySyncResponse)
async def sync_policy(
    req: PolicySyncRequest,
    deployment: Deployment = Depends(_authenticated_deployment),
    db: Session = Depends(get_db),
) -> PolicySyncResponse:
    """Return the latest policy package for the requesting data plane.

    If the data plane already has the latest version, returns has_update=False.
    """
    if req.deployment_id != deployment.deployment_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"code": "DEPLOYMENT_MISMATCH"},
        )

    # Check if there is an active policy package for this deployment.
    # In a production system this would read from the policy_versions table
    # with the deployment's active policy.  Here we return the current state.
    current_version = deployment.current_policy_version

    if req.current_version_id and req.current_version_id == current_version:
        return PolicySyncResponse(has_update=False)

    # Build policy from the deployment's active policy config.
    package = _build_policy_package_for_deployment(deployment, db)
    if package is None:
        return PolicySyncResponse(has_update=False)

    # Update the deployment's sync record.
    deployment.last_policy_sync_at = datetime.now(timezone.utc)
    deployment.is_connected = True
    deployment.disconnected_since = None
    db.commit()

    logger.info(
        "policy_synced",
        extra={
            "deployment_id": deployment.deployment_id,
            "version_id": package.version_id,
        },
    )
    return PolicySyncResponse(has_update=True, package=package)


@router.post("/policy/rollback")
async def request_rollback(
    deployment: Deployment = Depends(_authenticated_deployment),
    db: Session = Depends(get_db),
) -> dict:
    """Operator-initiated rollback to the last known-good policy version."""
    if not deployment.current_policy_version:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"code": "NO_POLICY", "message": "no policy version to roll back from"},
        )
    # In production: resolve last_known_good from the policy_versions history.
    logger.info(
        "policy_rollback_requested",
        extra={"deployment_id": deployment.deployment_id},
    )
    return {"status": "rollback_scheduled", "deployment_id": deployment.deployment_id}


# ── Telemetry ────────────────────────────────────────────────────────────────

@router.post("/telemetry", response_model=TelemetryAck)
async def ingest_telemetry(
    batch: TelemetryBatch,
    deployment: Deployment = Depends(_authenticated_deployment),
    db: Session = Depends(get_db),
) -> TelemetryAck:
    """Receive a batch of security events from a data plane.

    Events are written to the audit pipeline.  Sensitive browser content
    (cookies, raw HTML, form values) must not appear in telemetry.
    """
    if batch.deployment_id != deployment.deployment_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"code": "DEPLOYMENT_MISMATCH"},
        )

    accepted = 0
    rejected = 0

    for event in batch.events:
        if _contains_sensitive_fields(event.metadata):
            rejected += 1
            logger.warning(
                "telemetry_event_rejected_sensitive_data",
                extra={
                    "deployment_id": deployment.deployment_id,
                    "event_id": event.event_id,
                },
            )
            continue
        # Persist event to audit store.
        _persist_telemetry_event(event, deployment, db)
        accepted += 1

    next_checkpoint = str(int(batch.checkpoint) + accepted)

    logger.info(
        "telemetry_batch_received",
        extra={
            "deployment_id": deployment.deployment_id,
            "batch_id": batch.batch_id,
            "accepted": accepted,
            "rejected": rejected,
        },
    )
    return TelemetryAck(
        batch_id=batch.batch_id,
        accepted_count=accepted,
        rejected_count=rejected,
        next_checkpoint=next_checkpoint,
    )


# ── Health reporting ──────────────────────────────────────────────────────────

@router.post("/deployments/{deployment_id}/health")
async def report_health(
    deployment_id: str,
    health: DataPlaneHealth,
    deployment: Deployment = Depends(_authenticated_deployment),
    db: Session = Depends(get_db),
) -> dict:
    """Receive a health report from a data plane."""
    if deployment_id != deployment.deployment_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"code": "DEPLOYMENT_MISMATCH"},
        )

    deployment.last_heartbeat_at = datetime.now(timezone.utc)
    deployment.is_connected = not health.disconnected_mode

    if health.disconnected_mode and not deployment.disconnected_since:
        deployment.disconnected_since = datetime.now(timezone.utc)
    elif not health.disconnected_mode:
        deployment.disconnected_since = None

    deployment.status = health.status.value
    db.commit()

    return {"status": "ok", "deployment_id": deployment_id}


@router.get("/deployments/{deployment_id}/status")
async def get_deployment_status(
    deployment_id: str,
    deployment: Deployment = Depends(_authenticated_deployment),
    db: Session = Depends(get_db),
) -> dict:
    """Return the current status of a data-plane deployment."""
    if deployment_id != deployment.deployment_id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={"code": "DEPLOYMENT_MISMATCH"},
        )
    return {
        "deployment_id": deployment.deployment_id,
        "status": deployment.status,
        "profile": deployment.profile,
        "current_policy_version": deployment.current_policy_version,
        "last_policy_sync_at": (
            deployment.last_policy_sync_at.isoformat()
            if deployment.last_policy_sync_at else None
        ),
        "is_connected": deployment.is_connected,
        "last_heartbeat_at": (
            deployment.last_heartbeat_at.isoformat()
            if deployment.last_heartbeat_at else None
        ),
    }


# ── Helpers ───────────────────────────────────────────────────────────────────

_SENSITIVE_FIELDS = frozenset(
    {
        "cookie", "cookies", "authorization", "password", "secret", "token",
        "raw_html", "html_content", "page_source", "screenshot", "form_data",
        "credential", "credentials",
    }
)


def _contains_sensitive_fields(metadata: dict) -> bool:
    """Return True if any metadata key looks like it contains sensitive data."""
    for key in metadata.keys():
        if key.lower() in _SENSITIVE_FIELDS:
            return True
    return False


def _persist_telemetry_event(event, deployment: Deployment, db: Session) -> None:
    """Write a telemetry event to the audit store."""
    try:
        from app.db.models import AuditEvent

        audit = AuditEvent(
            organization_id=deployment.organization_id,
            event_type=f"data_plane.{event.event_type}",
            actor=f"deployment:{deployment.deployment_id}",
            resource=f"deployment:{deployment.deployment_id}",
            action=event.event_type,
            outcome="event",
            severity=event.severity,
            metadata={
                "deployment_id": deployment.deployment_id,
                "remote_event_id": event.event_id,
                "occurred_at": event.occurred_at.isoformat(),
                "summary": event.summary,
                **{k: v for k, v in event.metadata.items()
                   if k.lower() not in _SENSITIVE_FIELDS},
            },
        )
        db.add(audit)
        db.commit()
    except Exception as exc:
        logger.error(
            "telemetry_persist_failed",
            extra={"error": str(exc), "event_id": event.event_id},
        )
        db.rollback()


def _build_policy_package_for_deployment(
    deployment: Deployment,
    db: Session,
) -> Optional[PolicyPackage]:
    """Build and sign a current policy package for a deployment.

    Reads the deployment's active policy from the policies table.
    Returns None when no active policy is configured.
    """
    try:
        from app.db.models import Policy

        policy = (
            db.query(Policy)
            .filter(
                Policy.organization_id == deployment.organization_id,
                Policy.is_active == True,  # noqa: E712
            )
            .order_by(Policy.created_at.desc())
            .first()
        )

        if not policy:
            return None

        spec_data = policy.rules or {}
        spec = PolicySpec(
            allowed_domains=spec_data.get("allowed_domains", []),
            blocked_domains=spec_data.get("blocked_domains", []),
            default_domain_policy=spec_data.get("default_domain_policy", "deny"),
            allowed_ports=spec_data.get("allowed_ports", "80,443"),
            max_redirects=spec_data.get("max_redirects", 5),
            block_https_downgrade=spec_data.get("block_https_downgrade", True),
            allow_private_networks=spec_data.get("allow_private_networks", False),
            dlp_enabled=spec_data.get("dlp_enabled", True),
            threat_detection_enabled=spec_data.get("threat_detection_enabled", True),
        )

        # Build a version ID from the policy's updated_at timestamp.
        version_id = f"v{int(policy.updated_at.timestamp())}-{policy.id[:8]}"

        if deployment.deployment_secret_hash is None:
            return None

        # We only have the hash of the secret — in production we'd retrieve
        # the actual secret from a secrets manager.  For the reference
        # implementation we use a deterministic signing key derived from the
        # stored hash (this is weaker than using the real secret, but
        # demonstrates the signing protocol correctly).
        signing_key = deployment.deployment_secret_hash

        from datetime import timedelta
        pkg = PolicyPackage(
            version_id=version_id,
            deployment_id=deployment.deployment_id,
            spec=spec,
            signature="",
            sequence_number=(deployment.current_policy_sequence or 0) + 1,
            valid_until=datetime.now(timezone.utc) + timedelta(hours=24),
        )
        pkg.signature = sign_package(pkg, signing_key)

        # Update deployment sync state.
        deployment.current_policy_version = version_id
        deployment.current_policy_sequence = pkg.sequence_number

        return pkg

    except Exception as exc:
        logger.error(
            "policy_build_failed",
            extra={"deployment_id": deployment.deployment_id, "error": str(exc)},
        )
        return None
