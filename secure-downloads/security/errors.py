"""Security error types for the secure-downloads module."""


class DownloadSecurityError(Exception):
    """
    Base class for all security violations in the secure-downloads module.

    Attributes
    ----------
    code:        Machine-readable error code (uppercase, underscore-separated).
    message:     Human-readable description (safe to surface to callers).
    http_status: Suggested HTTP status code for API responses.
    """

    def __init__(self, code: str, message: str, *, http_status: int = 403) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.http_status = http_status


