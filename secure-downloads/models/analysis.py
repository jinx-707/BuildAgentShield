"""
Document-analysis job model and state machine.

One analysis job exists per download (enforced by a UNIQUE constraint on
download_id).  The job records only metadata and the normalized analysis
result; document content is never stored in the database.

State machine
-------------
    PENDING ──claim──→ RUNNING ──→ COMPLETED   (terminal)
       ↑                  │
       │                  ├──→ FAILED ──retry──→ PENDING
       │                  ├──→ PENDING  (worker shutdown / crash recovery)
       │                  └──→ CANCELLED
       └── explicit cancel / retry

Only APPROVED downloads may have a job.  Quarantined, rejected, failed or
expired downloads are rejected by the service before a job is created.
"""
from __future__ import annotations

import enum
from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column

from models.database import Base


class AnalysisState(str, enum.Enum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


_VALID_TRANSITIONS: frozenset[tuple[AnalysisState, AnalysisState]] = frozenset(
    [
        (AnalysisState.PENDING, AnalysisState.RUNNING),
        (AnalysisState.PENDING, AnalysisState.CANCELLED),
        (AnalysisState.RUNNING, AnalysisState.COMPLETED),
        (AnalysisState.RUNNING, AnalysisState.FAILED),
        (AnalysisState.RUNNING, AnalysisState.PENDING),   # requeue on shutdown
        (AnalysisState.RUNNING, AnalysisState.CANCELLED),
        (AnalysisState.FAILED, AnalysisState.PENDING),    # manual retry
    ]
)


class AnalysisStateError(Exception):
    """Raised when an invalid analysis-state transition is attempted."""

    def __init__(self, current: AnalysisState, requested: AnalysisState) -> None:
        super().__init__(f"Invalid analysis transition: {current.value} → {requested.value}")
        self.current = current
        self.requested = requested


def assert_valid_analysis_transition(
    current: AnalysisState, target: AnalysisState
) -> None:
    if (current, target) not in _VALID_TRANSITIONS:
        raise AnalysisStateError(current, target)


def _utcnow() -> datetime:
    return datetime.now(tz=timezone.utc)


class DocumentAnalysis(Base):
    """Persisted analysis job and its normalized result."""

    __tablename__ = "document_analyses"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    download_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("downloads.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )
    tenant_id: Mapped[str] = mapped_column(String(128), nullable=False, index=True)

    state: Mapped[AnalysisState] = mapped_column(
        Enum(AnalysisState, name="analysis_state"),
        nullable=False,
        default=AnalysisState.PENDING,
        index=True,
    )
    provider: Mapped[str] = mapped_column(String(32), nullable=False)

    # Correlation ID generated by this service and echoed by the provider;
    # provider_analysis_id is the provider's own identifier.
    correlation_id: Mapped[str] = mapped_column(String(64), nullable=False)
    provider_analysis_id: Mapped[str | None] = mapped_column(String(128), nullable=True)

    attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    error_code: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # A safe, fixed failure description — never raw provider output.
    error_detail: Mapped[str | None] = mapped_column(Text, nullable=True)
    retryable: Mapped[bool | None] = mapped_column(Boolean, nullable=True)

    # Normalized analysis result (JSON text).  Never document content.
    result_json: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=_utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=_utcnow, onupdate=_utcnow
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    def transition_to(self, target: AnalysisState) -> None:
        assert_valid_analysis_transition(self.state, target)
        self.state = target
        self.updated_at = _utcnow()

    def __repr__(self) -> str:
        return (
            f"<DocumentAnalysis id={self.id!r} download={self.download_id!r} "
            f"state={self.state.value!r}>"
        )
